#!/usr/bin/env python3
"""Deploy cross-seed on grey (sylveste-aado.5).

Cross-seeding announces data grey ALREADY holds to a second tracker that carries
a byte-identical torrent. Upload credit on two trackers for zero extra disk and
zero extra download -- the best ratio lever available here.

`crossseed_assess.py` measured where the overlap actually is: 8/22 sampled
HDBits torrents have a size-matched twin elsewhere (36%), and six of those eight
are on TorrentLeech rather than Karagarga. Karagarga managed 2/22 (9%). So the
pairing that matters is HDBits <-> TorrentLeech; KG is included anyway because
it costs nothing to search and did produce two hits.

SAFETY, in the order it matters:

  * This does NOT create a two-IP violation. Cross-seeding produces a NEW
    infohash on a DIFFERENT tracker, seeded only from grey. The rule -- never
    seed the SAME torrent from two IPs -- is about one infohash on two machines.
    That is a real and separate problem here (see sylveste-inxe: 432 infohashes
    are loaded on both jarmusch and grey) but it is orthogonal to this.
  * matchMode "safe" only accepts matches whose file sizes line up exactly.
    Size proximity was good enough to *assess* the opportunity; it is not good
    enough to *announce*, so cross-seed verifies properly before injecting.
  * skipRecheck is false, so qBittorrent hashes the data before it announces.
    Announcing data we cannot actually serve is how a tracker learns to
    distrust you.
  * delay 30 paces searches. The point of ratio work is to protect standing on
    these trackers, so hammering their search endpoints would be self-defeating.
  * Injected torrents land in qBittorrent like any other, so qbit-manage tags
    them by tracker and applies the right share-limit group. Every group is
    cleanup:false, so nothing here can delete a torrent.

SECRETS. config.js needs the Prowlarr API key and qBittorrent credentials, so it
is GENERATED ON GREY from each service's own config and written 0600. This
script is safe to commit; the file it produces is not, and is not in the repo.

Usage:  crossseed_setup.py            write config only (no searching)
        crossseed_setup.py --search N run a bounded search over N torrents
"""
import argparse
import json
import re
import subprocess

CFG = "/home/mk/grey-media/config"
CS_DIR = "%s/cross-seed" % CFG
IMAGE = "ghcr.io/cross-seed/cross-seed:latest"
NETWORK = "grey-media_default"
# HDBits and TorrentLeech are where the overlap actually is; Karagarga is along
# for the ride because searching it is free and it produced two hits in 22.
INDEXER_IDS = [1, 2, 3]
DATA_DIRS = ["/data/movies", "/data/torrents/tv", "/data/torrents/race",
             "/data/downloads/complete"]
LINK_DIR = "/data/cross-seeds"


def prowlarr_key():
    return re.search(r"<ApiKey>([^<]+)</ApiKey>",
                     open("%s/prowlarr/config.xml" % CFG).read()).group(1).strip()


def qbit_creds():
    import yaml
    q = yaml.safe_load(open("%s/qbit-manage/config.yml" % CFG))["qbt"]
    return q.get("user"), q.get("pass")


def write_config():
    key = prowlarr_key()
    user, pw = qbit_creds()
    torznab = ["http://prowlarr:9696/%d/api?apikey=%s" % (i, key) for i in INDEXER_IDS]
    cfg = """// GENERATED by ops/zklw-media/library/crossseed_setup.py -- do not edit by hand.
// Contains live credentials; never commit this file.
module.exports = {
  torznab: %s,
  dataDirs: %s,
  linkDirs: [%s],
  linkType: "hardlink",
  matchMode: "safe",
  action: "inject",
  qbittorrentUrl: "http://%s:%s@qbittorrent:8080",
  outputDir: "/config",
  delay: 30,
  includeSingleEpisodes: false,
  includeNonVideos: false,
  duplicateCategories: false,
  linkCategory: "cross-seed",
  skipRecheck: false,
  seasonFromEpisodes: null,
  flatLinking: false,
  apiAuth: false,
  port: 2468,
  host: "0.0.0.0",
  searchCadence: null,
  rssCadence: null,
  snatchTimeout: "60 seconds",
  searchTimeout: "120 seconds",
  searchLimit: 0,
  blockList: []
};
""" % (json.dumps(torznab), json.dumps(DATA_DIRS), json.dumps(LINK_DIR),
       user, pw)
    import os
    os.makedirs(CS_DIR, exist_ok=True)
    p = "%s/config.js" % CS_DIR
    with open(p, "w") as f:
        f.write(cfg)
    os.chmod(p, 0o600)
    os.chown(p, 1001, 1001)
    try:
        os.chown(CS_DIR, 1001, 1001)
    except OSError:
        pass
    print("wrote %s (0600, uid 1001)" % p)
    print("  torznab indexers: %s" % INDEXER_IDS)
    print("  dataDirs: %s" % DATA_DIRS)
    print("  matchMode=safe  action=inject  skipRecheck=false  delay=30s")


def run(args):
    cmd = ["docker", "run", "--rm", "--user", "1001:1001", "--network", NETWORK,
           "-v", "%s:/config" % CS_DIR, "-v", "/data:/data", IMAGE] + args
    print("$ %s" % " ".join(cmd))
    p = subprocess.run(cmd, capture_output=True, text=True, timeout=5400)
    print(p.stdout[-9000:])
    if p.stderr.strip():
        print("--- stderr ---")
        print(p.stderr[-3000:])
    return p.returncode


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--search", type=int, default=0,
                    help="run a bounded search over N torrents")
    a = ap.parse_args()
    write_config()
    if a.search:
        run(["search", "--search-limit", str(a.search)])


main()
